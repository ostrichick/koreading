/**
 * 지정된 토픽 ID에서 무작위 세부 소재(Sub-topic Seed)를 하나 반환합니다.
 */
export function getRandomSubTopic(topicId: string): string {
  const seeds = TOPIC_SUBSEEDS[topicId];
  if (!seeds || seeds.length === 0) {
    return '한국의 흥미롭고 독창적인 일상과 문화 이야기';
  }
  const idx = Math.floor(Math.random() * seeds.length);
  return seeds[idx];
}

/**
 * 장르 ID에 해당하는 프롬프트 지침을 반환합니다.
 */
export function getGenreInstruction(genreId?: string): string {
  const genre = GENRE_OPTIONS.find(g => g.id === genreId);
  return genre ? genre.instruction : GENRE_OPTIONS[0].instruction;
}
